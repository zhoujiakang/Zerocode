CREATE TABLE IF NOT EXISTS `user` (
 id BIGINT AUTO_INCREMENT PRIMARY KEY,
 userAccount VARCHAR(256) NOT NULL,
 userPassword VARCHAR(512) NOT NULL,
 userName VARCHAR(256), userAvatar VARCHAR(1024), userProfile VARCHAR(512),
 userRole VARCHAR(256) DEFAULT 'user' NOT NULL,
 editTime TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP NOT NULL,
 createTime TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
 updateTime TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP NOT NULL,
 isDelete TINYINT DEFAULT 0 NOT NULL,
 CONSTRAINT uk_userAccount UNIQUE(userAccount)
);
CREATE INDEX IF NOT EXISTS idx_userName ON `user` (userName);
